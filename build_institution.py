#!/usr/bin/env python3
"""
Build an institution-specific version of the grader with Briefcase.

This script copies the project to a temp directory, writes that copy's
institution.py (and tweaks its pyproject.toml so each institution gets its own
bundle id / app name), runs briefcase there, and copies the results into
./dist/<slug>/

Institutions live in institutions.json (add it to .gitignore):

    {
      "psu": {
        "name": "Penn State",
        "base_url": "https://psu.instructure.com",
        "client_id": "12345",
        "redirect_port": 53682,
        "allow_token_login": false
      }
    }

The client secret is never read from that file. Provide it via the
CANVAS_CLIENT_SECRET_<SLUG> environment variable (slug upper-cased), e.g.
CANVAS_CLIENT_SECRET_PSU, or you'll be prompted for it.

Usage:
    python build_institution.py psu
    python build_institution.py psu --steps create build
    python build_institution.py psu -- --adhoc-sign        # extra args go to `briefcase package`
    python build_institution.py --all
    python build_institution.py --list
"""

import argparse
import getpass
import json
import os
import pprint
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONFIG_FILE = ROOT / "institutions.json"
DIST_DIR = ROOT / "dist"

REQUIRED_FIELDS = ("name", "base_url", "client_id")
SLUG_RE = re.compile(r"^[a-z][a-z0-9]*$")

IGNORE = shutil.ignore_patterns(
    ".git", ".venv", "venv", "build", "dist", "logs", ".briefcase",
    "__pycache__", "*.pyc", "institutions.json",
)


def die(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def load_institutions():
    try:
        data = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))
    except FileNotFoundError:
        die(f"{CONFIG_FILE.name} not found (see the docstring at the top of this script)")
    except json.JSONDecodeError as e:
        die(f"{CONFIG_FILE.name} is not valid JSON: {e}")

    for slug, inst in data.items():
        if not SLUG_RE.match(slug):
            die(f"slug '{slug}' must be lowercase letters/digits, starting with a letter")
        missing = [f for f in REQUIRED_FIELDS if not inst.get(f)]
        if missing:
            die(f"institution '{slug}' is missing: {', '.join(missing)}")
    return data


def get_secret(slug):
    env = f"CANVAS_CLIENT_SECRET_{slug.upper()}"
    secret = os.environ.get(env)
    if secret:
        return secret
    if sys.stdin.isatty():
        secret = getpass.getpass(f"Client secret for '{slug}' (or set {env}): ")
        if secret:
            return secret
    die(f"no client secret for '{slug}'. Set {env}.")


def write_institution_module(project_dir, slug, inst, secret):
    candidates = list((project_dir / "src").glob("*/institution.py"))
    if len(candidates) != 1:
        die(f"expected exactly one src/*/institution.py, found {len(candidates)}")

    value = {
        "name": inst["name"],
        "base_url": inst["base_url"].rstrip("/"),
        "client_id": str(inst["client_id"]),
        "client_secret": secret,
        "redirect_port": int(inst.get("redirect_port", 53682)),
        "allow_token_login": bool(inst.get("allow_token_login", False)),
    }
    candidates[0].write_text(
        "# GENERATED by build_institution.py. Do not commit.\n"
        f"INSTITUTION = {pprint.pformat(value, sort_dicts=False)}\n",
        encoding="utf-8",
    )


def patch_pyproject(project_dir, slug, inst):
    """Give each institution its own bundle id and display name so installs
    don't collide and each gets its own config directory."""
    path = project_dir / "pyproject.toml"
    text = path.read_text(encoding="utf-8")

    # Top-level [tool.briefcase] bundle, e.g. "com.example" -> "com.example.psu"
    text, n = re.subn(
        r'^(bundle\s*=\s*")([^"]+)(")',
        lambda m: f"{m.group(1)}{m.group(2)}.{slug}{m.group(3)}",
        text, count=1, flags=re.MULTILINE,
    )
    if n != 1:
        die("couldn't find a `bundle = \"...\"` line in pyproject.toml")

    # App display name, e.g. "Spree Grader" -> "Spree Grader Penn State"
    def rename(m):
        new = inst.get("formal_name") or f"{m.group(2)} {inst['name']}"
        return f'{m.group(1)}{new}{m.group(3)}'

    text, n = re.subn(
        r'^(formal_name\s*=\s*")([^"]+)(")', rename,
        text, count=1, flags=re.MULTILINE,
    )
    if n != 1:
        die("couldn't find a `formal_name = \"...\"` line in pyproject.toml")

    path.write_text(text, encoding="utf-8")


def run_briefcase(project_dir, step, extra):
    cmd = [sys.executable, "-m", "briefcase", step, "--no-input"]
    if step == "package":
        cmd += extra
    print(f"\n$ {' '.join(cmd)}")
    subprocess.run(cmd, cwd=project_dir, check=True)


def build_one(slug, inst, steps, extra):
    print(f"\n=== Building '{slug}' ({inst['name']}) ===")
    secret = get_secret(slug)

    with tempfile.TemporaryDirectory(prefix=f"grader-{slug}-") as tmp:
        work = Path(tmp) / "project"
        shutil.copytree(ROOT, work, ignore=IGNORE)
        write_institution_module(work, slug, inst, secret)
        patch_pyproject(work, slug, inst)

        for step in steps:
            run_briefcase(work, step, extra)

        built = work / "dist"
        if built.is_dir() and any(built.iterdir()):
            out = DIST_DIR / slug
            if out.exists():
                shutil.rmtree(out)
            shutil.copytree(built, out)
            print(f"\nArtifacts for '{slug}' copied to {out}")
        elif "package" in steps:
            print("warning: package step ran but no dist/ output was found")


def main():
    argv = sys.argv[1:]
    extra = []
    if "--" in argv:
        i = argv.index("--")
        argv, extra = argv[:i], argv[i + 1:]

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("slugs", nargs="*", help="institution slug(s) from institutions.json")
    ap.add_argument("--all", action="store_true", help="build every institution")
    ap.add_argument("--list", action="store_true", help="list configured institutions")
    ap.add_argument("--steps", nargs="+", default=["create", "build", "package"],
                    choices=["create", "update", "build", "package"],
                    help="briefcase steps to run (default: create build package)")
    args = ap.parse_args(argv)

    institutions = load_institutions()

    if args.list:
        for slug, inst in institutions.items():
            print(f"{slug:15} {inst['name']} ({inst['base_url']})")
        return

    slugs = list(institutions) if args.all else args.slugs
    if not slugs:
        ap.error("give at least one slug, or use --all / --list")
    unknown = [s for s in slugs if s not in institutions]
    if unknown:
        die(f"unknown institution(s): {', '.join(unknown)}")

    for slug in slugs:
        try:
            build_one(slug, institutions[slug], args.steps, extra)
        except subprocess.CalledProcessError as e:
            die(f"briefcase failed for '{slug}' (exit {e.returncode})")


if __name__ == "__main__":
    main()